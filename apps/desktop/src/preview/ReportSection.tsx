// The project report on the daemon's own generated view (simulated music channel), in every state that
// can be made from it, with no daemon: a verdict, a pin and Recompose answer locally.

import { useState } from "react";
import { ReportBody } from "../main/report/Report";
import { genresOf } from "../main/report/format";
import { REPORT_STATES } from "./reportStates";

const pause = (ms: number) => new Promise((r) => setTimeout(r, ms));

export function ReportSection() {
  const [at, setAt] = useState(0);
  const [pinned, setPinned] = useState<Record<string, string[]>>({});
  const named = REPORT_STATES[at]!;
  const view = named.state.view;
  const state = view && pinned[named.name] ? { ...named.state, view: { ...view, pinned: pinned[named.name]! } } : named.state;
  const genres = view ? genresOf(view.values["d-tracks"]?.items ?? []) : [];

  return (
    <section className="pv-section" aria-labelledby="pv-report">
      <h2 id="pv-report">Report (simulated music channel, generated by the daemon)</h2>
      <div className="pv-row" role="group" aria-label="Report state">
        {REPORT_STATES.map((s, i) => (
          <button key={s.name} type="button" className={i === at ? "btn btn-primary" : "btn"} aria-pressed={i === at} onClick={() => setAt(i)}>
            {s.name}
          </button>
        ))}
      </div>
      <div className="pv-report" key={named.name}>
        <ReportBody
          state={state}
          now={named.now}
          genres={genres}
          onRetry={() => setAt(0)}
          onRecompose={() => setAt(REPORT_STATES.findIndex((s) => s.name === "arranged"))}
          onPin={async (id, on) => {
            await pause(150);
            const was = state.view?.pinned ?? [];
            setPinned((p) => ({ ...p, [named.name]: on ? [...was.filter((x) => x !== id), id] : was.filter((x) => x !== id) }));
          }}
          onVerdict={() => pause(250)}
          onDecide={async () => {
            throw new Error("no cards in this view");
          }}
        />
      </div>
    </section>
  );
}
