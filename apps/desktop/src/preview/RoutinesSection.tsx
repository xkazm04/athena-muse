// What Athena does on her own, on the routines the daemon generated (simulated channel) and the reasons
// derived from them, with no daemon: Pause, Resume, a page and Run now answer locally.

import { useState } from "react";
import type { Routine, RoutineBody } from "../lib/contract";
import { RoutinesBody } from "../main/report/Routines";
import { ROUTINE_STATES, ROUTINES_NOW, runsOf } from "./routineStates";

const pause = (ms: number) => new Promise((r) => setTimeout(r, ms));

export function RoutinesSection() {
  const [at, setAt] = useState(0);
  const [lists, setLists] = useState<Record<string, Routine[]>>({});
  const named = ROUTINE_STATES[at]!;
  const list = lists[named.name] ?? named.state.list;
  const put = (id: string, change: (r: Routine) => Routine) => setLists((l) => ({ ...l, [named.name]: list.map((r) => (r.id === id ? change(r) : r)) }));

  return (
    <section className="pv-section" aria-labelledby="pv-routines">
      <h2 id="pv-routines">Routines (simulated channel, generated by the daemon; the other reasons derived)</h2>
      <div className="pv-row" role="group" aria-label="Routines state">
        {ROUTINE_STATES.map((s, i) => (
          <button key={s.name} type="button" className={i === at ? "btn btn-primary" : "btn"} aria-pressed={i === at} onClick={() => setAt(i)}>
            {s.name}
          </button>
        ))}
      </div>
      <div className="pv-routines" key={named.name}>
        <RoutinesBody
          state={{ ...named.state, list }}
          now={ROUTINES_NOW}
          onChange={async (id, body: RoutineBody) => {
            await pause(200);
            put(id, (r) => ({ ...r, ...body, ...(body.state === "paused" ? { next_at: undefined } : {}) }));
          }}
          onRun={async (id) => {
            await pause(900);
            // the run the daemon recorded last for it, ended now
            put(id, (r) => (r.last_run ? { ...r, last_run: { ...r.last_run, ended: ROUTINES_NOW.toISOString() } } : r));
          }}
          onRuns={async (id) => {
            await pause(150);
            return runsOf(id.replace(/-[a-z_]+$/, ""));
          }}
          onSignIn={() => undefined}
          onRetry={() => setAt(0)}
        />
      </div>
    </section>
  );
}
