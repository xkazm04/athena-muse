"""Generate the stage's staged conversation in wire shape (onboarding v2, ADR 0007).

Reads `apps/desktop/src/main/stage/fixture/conversation.src.json` (invented data) and writes
`staged.ts` beside it. Every sketch change goes through the daemon's own `sketch.apply`, `confirm`
and `coverage`, so the fixture cannot draw what a live draft would refuse.

    uv run python scripts/stage_fixture.py          # write staged.ts
    uv run python scripts/stage_fixture.py --check  # exit 1 when staged.ts is out of date
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Any, cast

from athena.contracts import BenchSummary, Draft, Sketch, SketchOp
from athena.drafts.rubric import agreed, coverage
from athena.drafts.sketch import apply, confirm, empty

FIXTURE = Path(__file__).resolve().parents[1] / "apps/desktop/src/main/stage/fixture"
SOURCE = FIXTURE / "conversation.src.json"
TARGET = FIXTURE / "staged.ts"

DRAFT_ID = "drf_00000000c1b0"
SPACE_ID = "spc_7a1c9e0d2b44"
REHEARSAL_SPACE = "spc_000000000001"  # the test run's throwaway daemon: its cards are never signable
START = datetime(2026, 10, 28, 15, 30, 0, tzinfo=UTC)
APP_IDS = {
    "Mail (practice)": "mail",
    "Oakridge Primary parent portal (practice)": "oakridge",
    "Brightside Parents (practice)": "brightside",
    "Brightside Parents": "brightside",
}
CHORE_ID = "club-invoice-check"
REGENERATE = "uv run python scripts/stage_fixture.py"

HEADER = """// GENERATED by scripts/stage_fixture.py from conversation.src.json - do not edit by hand.
// Invented data: every name, date, amount and app here is made up for the stage's preview and tests.

import type { Staged } from "./types";

export const STAGED: Staged = """


class Clock:
    def __init__(self) -> None:
        self.t = START

    def tick(self, seconds: float) -> str:
        self.t += timedelta(seconds=seconds)
        return self.now()

    def now(self) -> str:
        return self.t.isoformat(timespec="seconds").replace("+00:00", "Z")


def draft(base: Draft, **changes: Any) -> Draft:
    out = cast("dict[str, Any]", json.loads(json.dumps(base)))
    out.update(changes)
    sketch = cast("Sketch", out["sketch"])
    out["coverage"] = coverage(sketch)
    out["agreed"] = agreed(out["coverage"])
    return cast("Draft", out)


def wire_ops(raw: list[dict[str, Any]], said: list[str]) -> list[SketchOp]:
    """The source's ops as the daemon takes them: an added node's origin decides `confirmed`, and a
    node is the person's only with a quote found in their own words (the daemon's rule)."""
    out: list[SketchOp] = []
    for op in raw:
        if op["op"] == "add":
            node = dict(op["node"])
            if node["origin"] == "you":
                quote = node.get("quote", "")
                if len(quote.split()) < 3 or not any(quote.casefold() in s.casefold() for s in said):
                    raise SystemExit(f"node {node['id']}: quote {quote!r} is not in the person's words")
            node["confirmed"] = node["origin"] == "you"
            out.append(cast("SketchOp", {"op": "add", "node": node}))
        else:
            out.append(cast("SketchOp", op))
    return out


def build() -> dict[str, Any]:
    src = json.loads(SOURCE.read_text(encoding="utf-8"))
    clock = Clock()
    created = clock.now()
    current = draft(
        cast(
            "Draft",
            {
                "id": DRAFT_ID,
                "space_id": SPACE_ID,
                "step": "describe",
                "need": src["need"],
                "sketch": empty(),
                "created": created,
                "updated": created,
            },
        )
    )
    first = current
    frames: list[dict[str, Any]] = []
    said = [src["need"]]
    for i, f in enumerate(src["frames"]):
        user = f["user"]
        say: dict[str, Any] = {"text": "" if i == 0 else user.get("text", "")}
        if user.get("choice"):
            say = {"text": "", "choice": user["choice"]}
        said.append(user.get("choice") or user.get("text", ""))
        sketch, applied = apply(current["sketch"], wire_ops(f["ops"], said))
        updated = clock.tick(f["elapsed_s"])
        current = draft(current, step="shape", sketch=sketch, updated=updated)
        if f.get("ask"):
            current["ask"] = f["ask"]
        else:
            cast("dict[str, Any]", current).pop("ask", None)
        turn_id = f"turn_00000000{i:04x}"
        events: list[dict[str, Any]] = [
            {"type": "start", "turn_id": turn_id, "engine": "claude_code", "simulated": False},
            {"type": "text", "delta": f["line"]},
            {"type": "sketch", "ops": applied},
        ]
        if f.get("ask"):
            events.append({"type": "ask", "ask": f["ask"]})
        events.append({"type": "coverage", "coverage": current["coverage"], "agreed": current["agreed"]})
        events.append({"type": "done", "turn_id": turn_id, "waiting": False})
        frame: dict[str, Any] = {"say": say, "elapsed_s": f["elapsed_s"], "events": events, "draft": current}
        if f.get("confirm"):
            inked, _ = confirm(current["sketch"], f["confirm"])
            current = draft(current, sketch=inked, updated=clock.tick(2))
            frame["confirm"] = {"node_ids": f["confirm"], "draft": current}
        frames.append(frame)

    agreed_draft = current
    a = src["author"]
    fields = {"writing": (), "repair": ("problems",), "written": ("chore_id",)}  # the contract's, no more
    author = [
        {"at_s": e["elapsed_s"], "event": {"type": e["t"], **{k: e[k] for k in fields[e["t"]]}}}
        for e in a["events"]
    ]
    practice = [
        {
            "app_id": APP_IDS[x["name"]],
            "name": x["name"].removesuffix(" (practice)"),
            "reads": x["reads"],
            "acts": x["acts"],
            "rows": x["rows"],
        }
        for x in a["practice_apps"]
    ]
    author[-1]["event"]["practice"] = practice
    stale = {k: v for k, v in agreed_draft.items() if k != "ask"}
    written = draft(
        cast("Draft", stale), step="preview", chore_id=CHORE_ID, practice=practice, updated=clock.tick(73)
    )
    failed = a["failed_alternative"]
    author_failed = [
        {"at_s": 0, "event": {"type": "writing"}},
        {"at_s": 41, "event": {"type": "repair", "problems": a["events"][1]["problems"]}},
        {"at_s": 88, "event": {"type": "repair", "problems": failed["problems"]}},
        {"at_s": 131, "event": {"type": "author_failed", "problems": failed["problems"]}},
    ]
    failed_draft = draft(agreed_draft, step="shape", updated=written["updated"])

    p = src["preview"]
    expected = [{**c, "app": APP_IDS[c["app"]]} for c in p["expected"]]
    previewed = draft(written, expected=expected, updated=clock.tick(p["elapsed_s"]))
    marks = []
    for m in p["marks"]:
        mark: dict[str, Any] = {"expected_id": m["expected_id"], "mark": m["mark"]}
        if m.get("user_note"):
            mark["note"] = m["user_note"]
        marks.append(mark)
    key_body = {"marks": marks, "missing": [x["text"] for x in p["missing"]], "never": p["never"]}
    missed = src["rehearsal"]["missed"][0]
    placed = {
        "id": "m1",
        "app": "brightside",
        "tool": "file_billing_query",
        "key": missed["key"],
        "label": "Query: the $15 late-pickup fee on Thu 16 Oct",
        "why": p["missing"][0]["text"],
    }
    key = {
        "marks": marks,
        "missing": [{"text": p["missing"][0]["text"], "expected": placed}],
        "never": [{"text": line} for line in p["never"]],  # no practice app can pay, so it stays words
    }
    keyed = draft(previewed, step="rehearse", key=key, updated=clock.tick(6))

    rehearsal: list[dict[str, Any]] = []
    bench: BenchSummary | None = None
    for e in src["rehearsal"]["events"]:
        if e["t"] == "phase":
            event: dict[str, Any] = {
                "type": "phase",
                "index": e["index"] + 1,
                "app": APP_IDS[e["app"]],
                "message": e["message"],
            }
        elif e["t"] == "card":
            c = e["card"]
            event = {
                "type": "card",
                "card": {
                    "id": c["id"],
                    "space_id": REHEARSAL_SPACE,
                    "action": "portal_act",
                    "label": c["label"],
                    "args": {  # as the daemon files a portal card: app, tool, params, chore
                        "app": APP_IDS[c["app"]],
                        "tool": c["tool"],
                        "params": {"line_id": c["key"]},
                        "chore": CHORE_ID,
                    },
                    "state": "waiting",
                    "created": (START + timedelta(seconds=e["at_s"])).isoformat().replace("+00:00", "Z"),
                },
            }
        else:
            bench = cast("BenchSummary", e["bench"])
            event = {"type": "scored", "bench": bench}
        rehearsal.append({"at_s": e["at_s"], "event": event})
    assert bench is not None
    scored = draft(keyed, step="verdict", bench=bench, updated=clock.tick(204))

    v = src["verdict"]
    verdict = {"verdict": "keep", "note": v["note"]}
    saved = draft(scored, step="saved", verdict="keep", note=v["note"], updated=clock.tick(9))
    revise = {"verdict": "revise", "note": v["revise_alternative"]["note"]}
    revised = draft(scored, step="shape", verdict="revise", note=revise["note"], updated=saved["updated"])

    s = src["saved"]
    project = {**s["project"], "id": SPACE_ID, "created": created, "updated": saved["updated"]}
    project["counts"] = {"episodes": len(frames), "facts": 0}
    chore = {
        "id": CHORE_ID,
        "title": s["chore"]["title"],
        "short_title": "The club's invoice, checked against attendance",
        "promise": s["project"]["brief"],
        "category": "consumer",
        "job": "contest",
        "senses": [],
        "featured": "unproven",
        "origin": "yours",
        "bench": bench,
    }
    return {
        "invented": src["invented"],
        "need": src["need"],
        "created": first,
        "frames": frames,
        "author": author,
        "written": written,
        "authorFailed": author_failed,
        "failedDraft": failed_draft,
        "preview": {"expected": expected},
        "previewed": previewed,
        "key": key_body,
        "keyed": keyed,
        "rehearsal": rehearsal,
        "scored": scored,
        "verdict": verdict,
        "saved": saved,
        "revise": revise,
        "revised": revised,
        "project": project,
        "chore": chore,
    }


def render() -> str:
    return HEADER + json.dumps(build(), ensure_ascii=False, indent=2) + ";\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="stage_fixture")
    parser.add_argument("--check", action="store_true", help="exit 1 when staged.ts is out of date")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current != text:
            print(f"{TARGET.name} is out of date; run: {REGENERATE}", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(FIXTURE.parents[5])}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
