# --- reading the prototypes' JS data ---------------------------------------------------------------


def js_object(path: Path, name: str) -> Any:
    """The object literal assigned to `window.<name>` in a prototype's data file, read as JSON: comments
    dropped, keys quoted, trailing commas removed. Strings are copied untouched."""
    text = path.read_text(encoding="utf-8")
    start = text.index("{", text.index(f"window.{name}"))
    out: list[str] = []
    i, depth = start, 0
    while True:
        c = text[i]
        if c in "\"'":
            j = i + 1
            while text[j] != c:
                j += 2 if text[j] == "\\" else 1
            body = text[i + 1 : j]
            out.append(json.dumps(json.loads(f'"{body}"') if c == '"' else body.replace("\\'", "'")))
            i = j + 1
            continue
        if text.startswith("//", i):
            i = text.index("\n", i)
            continue
        if c.isalpha() or c == "_":
            m = re.match(r"[A-Za-z_]\w*", text[i:])
            assert m
            word = m.group(0)
            rest = text[i + len(word) :].lstrip()
            out.append(json.dumps(word) if rest.startswith(":") else word)
            i += len(word)
            continue
        if c == "{" or c == "[":
            depth += 1
        elif c == "}" or c == "]":
            depth -= 1
            while out and out[-1].strip() == "":
                out.pop()
            if out and out[-1] == ",":
                out.pop()
        out.append(c)
        i += 1
        if depth == 0:
            break
    return json.loads("".join(out))


# --- the contract check ----------------------------------------------------------------------------


def check(value: Any, tp: Any, path: str) -> None:
    """Raises when `value` is not `tp` as contracts.py declares it."""
    if tp is Any:
        return
    origin = get_origin(tp)
    if origin is Literal:
        if value not in get_args(tp):
            raise SystemExit(f"{path}: {value!r} is not one of {get_args(tp)}")
        return
    if origin in (Union, types.UnionType):
        problems = []
        for arm in get_args(tp):
            try:
                check(value, arm, path)
                return
            except SystemExit as e:
                problems.append(str(e))
        raise SystemExit(f"{path}: {value!r} fits none of {tp}: {problems}")
    if origin is list:
        if not isinstance(value, list):
            raise SystemExit(f"{path}: expected a list")
        for i, v in enumerate(value):
            check(v, get_args(tp)[0], f"{path}[{i}]")
        return
    if origin is dict:
        if not isinstance(value, dict):
            raise SystemExit(f"{path}: expected an object")
        for k, v in value.items():
            check(k, get_args(tp)[0], f"{path}.<key>")
            check(v, get_args(tp)[1], f"{path}.{k}")
        return
    if isinstance(tp, type) and typing.is_typeddict(tp):
        if not isinstance(value, dict):
            raise SystemExit(f"{path}: expected {tp.__name__}")
        hints = typing.get_type_hints(tp, localns=globals(), include_extras=True)
        # contracts.py defers its annotations, so NotRequired is read from the hints, not __required_keys__
        required = [k for k, h in hints.items() if get_origin(h) is not NotRequired]
        missing = [k for k in required if k not in value]
        unknown = [k for k in value if k not in hints]
        if missing or unknown:
            raise SystemExit(f"{path} ({tp.__name__}): missing {missing}, unknown {unknown}")
        for k, v in value.items():
            if v is None:
                raise SystemExit(f"{path}.{k}: null; an absent value is an omitted key")
            hint = hints[k]
            if get_origin(hint) in (NotRequired, Required):
                hint = get_args(hint)[0]
            check(v, hint, f"{path}.{k}")
        return
    if tp is float:
        if not isinstance(value, int | float) or isinstance(value, bool):
            raise SystemExit(f"{path}: expected a number, got {value!r}")
        return
    if tp is int:
        if not isinstance(value, int) or isinstance(value, bool):
            raise SystemExit(f"{path}: expected a whole number, got {value!r}")
        return
    if not isinstance(value, tp):
        raise SystemExit(f"{path}: expected {tp}, got {value!r}")


def plain_words(value: Any, path: str = "fixture") -> None:
    """Every string a person could read uses plain words (SCHEMA.md "Words")."""
    if isinstance(value, str):
        hit = BANNED.search(value)
        if hit:
            raise SystemExit(f"{path}: {value!r} says {hit.group(0)!r}")
    elif isinstance(value, dict):
        for k, v in value.items():
            if k not in ("op", "type"):  # the wire's own key words, never shown
                plain_words(v, f"{path}.{k}")
    elif isinstance(value, list):
        for i, v in enumerate(value):
            plain_words(v, f"{path}[{i}]")


