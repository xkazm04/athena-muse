def render() -> str:
    return HEADER + json.dumps(build(), ensure_ascii=False, indent=2) + ";\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="twin_fixture")
    parser.add_argument("--check", action="store_true", help="exit 1 when twins.ts is out of date")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current != text:
            print(f"{TARGET.name} is out of date; run: {REGENERATE}", file=sys.stderr)
            return 1
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
